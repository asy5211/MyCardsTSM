-- ----------------------------------------------------------------------------
-- Accounts
-- ----------------------------------------------------------------------------

CREATE TABLE users (
  id                 CHAR(36)     NOT NULL,
  username           VARCHAR(30)  NOT NULL,
  email              VARCHAR(255) NOT NULL,
  password_hash      VARCHAR(255) NOT NULL,              -- bcrypt; never the password
  phone              VARCHAR(30)  NULL,
  avatar_key         VARCHAR(255) NULL,                  -- object-storage key of profile picture
  status             ENUM('active','suspended','deleted') NOT NULL DEFAULT 'active',
  terms_accepted_at  DATETIME(3)  NOT NULL,              -- required at sign-up (spec 2)
  terms_version      VARCHAR(20)  NOT NULL DEFAULT '1.0',
  email_verified_at  DATETIME(3)  NULL,
  last_login_at      DATETIME(3)  NULL,
  deleted_at         DATETIME(3)  NULL,                  -- account deletion (App Store rule)
  created_at         DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at         DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_users_username (username),
  UNIQUE KEY uq_users_email (email)
  -- On account deletion: set status='deleted', deleted_at=now, and overwrite
  -- username/email/phone/avatar_key with anonymised values (e.g.
  -- 'deleted_<id8>' and 'deleted+<id>@deleted.invalid') so orders can keep
  -- their history without keeping personal data.
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- One saved shipping address per person (schema v1.1). Checkout asks for it
-- when it is missing. Orders will copy it at purchase time, so editing it later
-- never rewrites an old order.
CREATE TABLE user_addresses (
  user_id      CHAR(36)     NOT NULL,
  full_name    VARCHAR(100) NOT NULL,
  line1        VARCHAR(120) NOT NULL,
  line2        VARCHAR(120) NULL,
  city         VARCHAR(80)  NOT NULL,
  region       VARCHAR(80)  NOT NULL,                 -- state / province
  postal_code  VARCHAR(20)  NOT NULL,
  country      CHAR(2)      NOT NULL DEFAULT 'US',    -- ISO 3166-1 alpha-2
  updated_at   DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (user_id),
  CONSTRAINT fk_address_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- Admin staff are a SEPARATE login population from app users, so a customer
-- token can never be mistaken for an admin token.
CREATE TABLE admin_staff (
  id             CHAR(36)     NOT NULL,
  email          VARCHAR(255) NOT NULL,
  name           VARCHAR(100) NOT NULL,
  password_hash  VARCHAR(255) NOT NULL,
  role           ENUM('super_admin','admin','support') NOT NULL DEFAULT 'admin',
  status         ENUM('active','disabled') NOT NULL DEFAULT 'active',
  last_login_at  DATETIME(3)  NULL,
  created_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_admin_staff_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- Password reset (deep link tsm://reset-password?token=...). Only a SHA-256
-- hash of the emailed token is stored, so a database leak can't be replayed.
CREATE TABLE password_reset_tokens (
  id          CHAR(36)  NOT NULL,
  user_id     CHAR(36)  NOT NULL,
  token_hash  CHAR(64)  NOT NULL,
  expires_at  DATETIME(3) NOT NULL,
  used_at     DATETIME(3) NULL,
  created_at  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_prt_token_hash (token_hash),
  KEY ix_prt_user (user_id),
  CONSTRAINT fk_prt_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

