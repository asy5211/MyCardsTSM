-- ============================================================================
-- TSM (The Sealed Market) - 01_schema.sql   (schema v1.3)
-- Target: MySQL 8.0.16+ / 8.4 LTS / 9.x   (needs CHECK constraints + generated columns)
--
-- Covers: accounts, admin staff, catalog (brands -> products -> listings),
--         seller applications + documents, audit log.
--         listing transparency fields, seller earnings + payouts (v1.2).
--         orders, reviews, messages, sell-to-us tickets, support requests,
--         seller payout methods and admin-editable fee settings (v1.3).
-- Later slices add: notifications, banners.
--
-- Conventions
--   * IDs are UUID strings, CHAR(36). Generated by the API, not the database.
--   * Money is DECIMAL(10,2) dollars here; the API sends integer cents.
--   * Timestamps are DATETIME(3) holding UTC. The backend connection must use
--     UTC (mysql2: timezone 'Z'; or run `SET time_zone = '+00:00'`).
--   * Collation utf8mb4_0900_ai_ci is accent- AND case-insensitive, so
--     'Pokemon' and 'Pokémon' are the same value (matches the app's
--     Product.belongs(to:) behaviour) and emails/usernames are case-insensitive.
--
-- Re-runnable: drops and recreates every table. DEV ONLY - this wipes data.
-- ============================================================================

