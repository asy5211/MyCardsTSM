-- A row exists only for APPROVED sellers. "Is this user an approved seller?"
-- is simply: EXISTS a seller_profiles row with status='active'.
CREATE TABLE seller_profiles (
  user_id               CHAR(36)      NOT NULL,
  display_name          VARCHAR(80)   NOT NULL,          -- store name shown on listings
  status                ENUM('active','suspended','revoked') NOT NULL DEFAULT 'active',  -- revoked = selling removed, account untouched (v1.3)
  rating_avg            DECIMAL(3,2)  NOT NULL DEFAULT 0.00,   -- recomputed from reviews (v1.3)
  rating_count          INT UNSIGNED  NOT NULL DEFAULT 0,
  sales_count           INT UNSIGNED  NOT NULL DEFAULT 0,      -- units sold, added to at checkout (v1.3)
  approved_at           DATETIME(3)   NOT NULL,
  approved_by_staff_id  CHAR(36)      NULL,
  suspended_at          DATETIME(3)   NULL,              -- set when TSM staff suspend the seller (v1.2)
  suspended_reason      VARCHAR(255)  NULL,
  revoked_at            DATETIME(3)   NULL,              -- set when TSM staff revoke selling (v1.3)
  revoked_reason        VARCHAR(255)  NULL,
  created_at            DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at            DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (user_id),
  UNIQUE KEY uq_seller_display_name (display_name),
  CONSTRAINT ck_seller_rating CHECK (rating_avg BETWEEN 0 AND 5),
  CONSTRAINT fk_seller_user  FOREIGN KEY (user_id)              REFERENCES users (id)       ON DELETE RESTRICT,
  CONSTRAINT fk_seller_staff FOREIGN KEY (approved_by_staff_id) REFERENCES admin_staff (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- One seller's offer against a product. A seller can only list if they have a
-- seller_profiles row (enforced by the foreign key).
--   * Seller sells out  -> quantity_available = 0 -> that row drops off the product page.
--   * Every seller out  -> product stays visible but grays out "SOLD OUT" (see v_product_summary).
CREATE TABLE listings (
  id                  CHAR(36)       NOT NULL,
  product_id          CHAR(36)       NOT NULL,
  seller_id           CHAR(36)       NOT NULL,           -- = seller_profiles.user_id
  price               DECIMAL(10,2)  NOT NULL,
  source              VARCHAR(100)   NOT NULL,           -- e.g. 'From Case', 'Loose Product'
  box_position        VARCHAR(40)    NULL,               -- e.g. 'Box 4 of 12' (built from box_number + boxes_in_case)
  condition_label     VARCHAR(60)    NOT NULL DEFAULT 'Factory Sealed',  -- CONDITION is a reserved word
  quantity_available  INT UNSIGNED   NOT NULL DEFAULT 0,
  is_active           TINYINT(1)     NOT NULL DEFAULT 1, -- 0 = the seller paused it
  -- Transparency fields (v1.2): where it came from and which box of the case it is.
  source_type         ENUM('distributor','retail_store','manufacturer_direct','other') NOT NULL DEFAULT 'distributor',
  distributor         VARCHAR(120)   NULL,               -- who the seller bought it from
  box_number          SMALLINT UNSIGNED NULL,            -- the 4 in 'Box 4 of 12'
  boxes_in_case       SMALLINT UNSIGNED NULL,            -- the 12 in 'Box 4 of 12'
  admin_hold          TINYINT(1)     NOT NULL DEFAULT 0, -- 1 = TSM staff took it off the shop (seller cannot undo)
  admin_hold_reason   VARCHAR(255)   NULL,
  created_at          DATETIME(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at          DATETIME(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY ix_listings_product_price (product_id, price),
  KEY ix_listings_seller (seller_id),
  CONSTRAINT ck_listings_price CHECK (price > 0),
  CONSTRAINT ck_listings_box CHECK (box_number IS NULL OR (boxes_in_case IS NOT NULL AND box_number BETWEEN 1 AND boxes_in_case)),
  CONSTRAINT fk_listings_product FOREIGN KEY (product_id) REFERENCES products (id)              ON DELETE CASCADE,
  CONSTRAINT fk_listings_seller  FOREIGN KEY (seller_id)  REFERENCES seller_profiles (user_id)  ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ----------------------------------------------------------------------------
-- Payouts (v1.2): what each seller has earned and what TSM has paid them.
-- Money here is integer cents. Rows in seller_earnings are written when an order
-- line is sold (lib/earnings.js); the checkout step will call it.
-- ----------------------------------------------------------------------------

CREATE TABLE payouts (
  id                    CHAR(36)     NOT NULL,
  seller_id             CHAR(36)     NOT NULL,
  amount_cents          INT UNSIGNED NOT NULL,
  earnings_count        INT UNSIGNED NOT NULL,
  status                ENUM('pending','paid','cancelled') NOT NULL DEFAULT 'pending',
  reference             VARCHAR(120) NULL,               -- bank / Shopify transfer id, entered when marked paid
  note                  VARCHAR(255) NULL,
  created_by_staff_id   CHAR(36)     NULL,
  created_at            DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  paid_at               DATETIME(3)  NULL,
  paid_by_staff_id      CHAR(36)     NULL,
  cancelled_at          DATETIME(3)  NULL,
  PRIMARY KEY (id),
  KEY ix_payouts_seller (seller_id, created_at),
  KEY ix_payouts_status (status),
  CONSTRAINT fk_payouts_seller   FOREIGN KEY (seller_id)           REFERENCES seller_profiles (user_id) ON DELETE RESTRICT,
  CONSTRAINT fk_payouts_creator  FOREIGN KEY (created_by_staff_id) REFERENCES admin_staff (id)          ON DELETE SET NULL,
  CONSTRAINT fk_payouts_payer    FOREIGN KEY (paid_by_staff_id)    REFERENCES admin_staff (id)          ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE seller_earnings (
  id                CHAR(36)     NOT NULL,
  seller_id         CHAR(36)     NOT NULL,
  listing_id        CHAR(36)     NULL,                   -- kept loosely; the snapshot below is what counts
  product_name      VARCHAR(160) NOT NULL,
  order_ref         VARCHAR(60)  NOT NULL,               -- the order number the sale belongs to
  quantity          INT UNSIGNED NOT NULL,
  unit_price_cents  INT UNSIGNED NOT NULL,
  gross_cents       INT UNSIGNED NOT NULL,               -- quantity x unit price
  commission_bps    SMALLINT UNSIGNED NOT NULL,          -- TSM commission in basis points (500 = 5.00%), as it was when the sale happened
  commission_cents  INT UNSIGNED NOT NULL,
  processing_fee_bps    SMALLINT UNSIGNED NOT NULL DEFAULT 0,   -- payment / Apple fee rate at the time of the sale (v1.3)
  processing_fee_cents  INT UNSIGNED NOT NULL DEFAULT 0,
  net_cents         INT UNSIGNED NOT NULL,               -- gross - commission - processing fee: what the seller is owed
  status            ENUM('available','in_payout','paid','reversed') NOT NULL DEFAULT 'available',
  payout_id         CHAR(36)     NULL,
  created_at        DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY ix_earnings_seller (seller_id, status),
  KEY ix_earnings_payout (payout_id),
  CONSTRAINT fk_earnings_seller  FOREIGN KEY (seller_id)  REFERENCES seller_profiles (user_id) ON DELETE RESTRICT,
  CONSTRAINT fk_earnings_listing FOREIGN KEY (listing_id) REFERENCES listings (id)             ON DELETE SET NULL,
  CONSTRAINT fk_earnings_payout  FOREIGN KEY (payout_id)  REFERENCES payouts (id)              ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ----------------------------------------------------------------------------
-- Seller applications (apply -> admin approval)
-- ----------------------------------------------------------------------------

CREATE TABLE seller_applications (
  id                   CHAR(36)      NOT NULL,
  user_id              CHAR(36)      NOT NULL,
  business_name        VARCHAR(160)  NOT NULL,
  business_address     VARCHAR(255)  NOT NULL,
  contact_email        VARCHAR(255)  NOT NULL,
  phone_number         VARCHAR(30)   NULL,
  source_type          ENUM('distributor','retail_store','manufacturer_direct','other','test') NOT NULL,
  distributor_list     TEXT          NOT NULL,           -- comma-separated; feeds the sell-to-us "Source" dropdown
  status               ENUM('submitted','under_review','approved','declined') NOT NULL DEFAULT 'submitted',
  is_test              TINYINT(1)    NOT NULL DEFAULT 0, -- demo "test" shortcut; server must ignore it in production
  decision_note        VARCHAR(500)  NULL,
  reviewed_by_staff_id CHAR(36)      NULL,
  reviewed_at          DATETIME(3)   NULL,
  submitted_at         DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at           DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  -- Trick for "only ONE open application per user": MySQL has no partial
  -- unique index, but UNIQUE ignores NULLs. This column is the user id while
  -- the application is open and NULL once it is approved/declined.
  open_for_user_id     CHAR(36) GENERATED ALWAYS AS (
                         CASE WHEN status IN ('submitted','under_review') THEN user_id ELSE NULL END
                       ) STORED,
  PRIMARY KEY (id),
  UNIQUE KEY uq_one_open_application (open_for_user_id),
  KEY ix_sellerapp_status (status, submitted_at),
  KEY ix_sellerapp_user (user_id),
  CONSTRAINT fk_sellerapp_user  FOREIGN KEY (user_id)              REFERENCES users (id)       ON DELETE RESTRICT,
  CONSTRAINT fk_sellerapp_staff FOREIGN KEY (reviewed_by_staff_id) REFERENCES admin_staff (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

